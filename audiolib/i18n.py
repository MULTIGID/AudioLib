def tr(value: object) -> str:
    text = str(value)
    if _active_language != "en":
        return text
    exact = UK_TO_EN.get(text)
    if exact is not None:
        return exact
    translated = text
    for source, target in PARTIAL_UK_TO_EN:
        translated = translated.replace(source, target)
    return translated
